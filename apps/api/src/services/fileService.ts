import { createWriteStream, existsSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import PDFDocument from 'pdfkit';
import { config } from '../config.js';

export const FILES_DIR = resolve(process.cwd(), 'data/files');

export interface PdfSection {
  heading: string;
  body: string;
}

export interface GeneratedFile {
  id: string;
  filename: string;
  path: string;
  url: string;
}

const slug = (value: string) =>
  value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'report';

/** Generate a clean A4 PDF and return its local path + public link. */
export async function generatePdf(input: {
  title: string;
  subtitle?: string;
  sections: PdfSection[];
}): Promise<GeneratedFile> {
  mkdirSync(FILES_DIR, { recursive: true });
  const id = randomUUID();
  const filename = `${slug(input.title)}-${id.slice(0, 8)}.pdf`;
  const filePath = join(FILES_DIR, filename);

  await new Promise<void>((resolvePromise, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 54 });
    const stream = createWriteStream(filePath);
    doc.pipe(stream);

    doc.fillColor('#111111').font('Helvetica-Bold').fontSize(22).text(input.title);
    if (input.subtitle) doc.moveDown(0.2).font('Helvetica').fontSize(10.5).fillColor('#555555').text(input.subtitle);
    doc.moveDown(0.4);
    doc.moveTo(54, doc.y).lineTo(541, doc.y).strokeColor('#d9d6cf').stroke();
    doc.moveDown(1);

    for (const section of input.sections) {
      doc.font('Helvetica-Bold').fontSize(12.5).fillColor('#111111').text(section.heading);
      doc.moveDown(0.25);
      doc.font('Helvetica').fontSize(10.5).fillColor('#333333').text(section.body, { lineGap: 3 });
      doc.moveDown(0.9);
      if (doc.y > 730) doc.addPage();
    }

    doc.fontSize(8.5).fillColor('#888888').text(
      `Generated by TEAMFORGE · ${new Date().toLocaleString('en-GB')}`,
      54,
      780,
      { align: 'right', width: 487 },
    );
    doc.end();
    stream.on('finish', () => resolvePromise());
    stream.on('error', reject);
  });

  const base = config.PUBLIC_BASE_URL || `http://127.0.0.1:${config.PORT}`;
  return { id, filename, path: filePath, url: `${base.replace(/\/$/, '')}/files/${filename}` };
}

export function resolveServedFile(name: string): string | null {
  if (!/^[a-z0-9._-]+\.pdf$/i.test(name)) return null;
  const filePath = join(FILES_DIR, name);
  return existsSync(filePath) ? filePath : null;
}
